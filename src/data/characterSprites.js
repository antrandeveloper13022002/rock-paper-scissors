// Pixel-art sprite data ported from Figma Make (32x32 grid + palette technique).
// Each build fn returns a 32x32 grid of palette-code strings (undefined = transparent).

const makeGrid = () => Array.from({ length: 32 }, () => new Array(32).fill(undefined));

function tools(g) {
  const f = (x1, y1, x2, y2, c) => {
    for (let y = y1; y <= y2; y += 1)
      for (let x = x1; x <= x2; x += 1) if (x >= 0 && x < 32 && y >= 0 && y < 32) g[y][x] = c;
  };
  const p = (x, y, c) => {
    if (x >= 0 && x < 32 && y >= 0 && y < 32) g[y][x] = c;
  };
  return { f, p };
}

